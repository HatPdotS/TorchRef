# Peak finding
# =============================================================================


def _circular_pad_gamma_alpha(x: torch.Tensor, r: int) -> torch.Tensor:
    """
    Wrap-pad axes 0 (γ) and -1 (α) by `r` voxels using circular boundary
    conditions, and constant-pad axis 1 (β) with -inf (non-periodic).
    Input shape (Γ, B, Α); output shape (Γ+2r, B+2r, Α+2r).
    """
    if r <= 0:
        return x
    x = torch.cat([x[-r:], x, x[:r]], dim=0)                    # wrap γ
    x = torch.cat([x[..., -r:], x, x[..., :r]], dim=-1)         # wrap α
    pad_shape = list(x.shape)
    pad_shape[1] = r
    neg_inf = torch.full(pad_shape, float("-inf"), dtype=x.dtype, device=x.device)
    x = torch.cat([neg_inf, x, neg_inf], dim=1)                 # β: -inf pad
    return x


def find_rotation_peaks(
    C: torch.Tensor,
    alphas: torch.Tensor,
    betas: torch.Tensor,
    gammas: torch.Tensor,
    n_peaks: int = 200,
    sigma_threshold: float = 0.0,
    cluster_radius_voxels: int = 2,
) -> List[RotationPeak]:
    """
    Extract local maxima of `C` and return them sorted by descending value.

    Periodic in α and γ (FFT axes); β is non-periodic but mirror at the
    endpoints isn't enforced — the user is expected to oversample β.

    Patterson centrosymmetry C(R) = C(-R) is left to the caller — when needed,
    add a post-processing step that merges peaks with R and -R representations.

    Vectorised over voxels: NMS is implemented as `C == max_pool3d(C)` with
    `kernel = 2·r + 1`, circular in α and γ. The legacy per-voxel Python loop
    with per-iteration `.item()` is replaced with a single sort + bulk
    `.tolist()` at the end — same semantics on randomly-real data (exact
    ties are vanishingly rare), but device-portable and ~1-2 orders of
    magnitude faster.
    """
    C_real = C.real
    n_gamma, n_beta, n_alpha = C_real.shape
    flat_stats = C_real.flatten()

    mean = flat_stats.mean()
    std = flat_stats.std().clamp(min=1e-30)
    threshold = mean + sigma_threshold * std

    r = int(cluster_radius_voxels)
    if r > 0:
        padded = _circular_pad_gamma_alpha(C_real, r)
        # max_pool3d wants (N, C, D, H, W). Add batch+channel dims, then strip.
        pooled = F.max_pool3d(
            padded.unsqueeze(0).unsqueeze(0),
            kernel_size=2 * r + 1, stride=1, padding=0,
        )[0, 0]
        is_local_max = C_real >= pooled
    else:
        is_local_max = torch.ones_like(C_real, dtype=torch.bool)

    above_threshold = C_real >= threshold
    candidate = is_local_max & above_threshold
    candidate_flat = candidate.flatten()
    cand_idx = candidate_flat.nonzero(as_tuple=False).flatten()
    if cand_idx.numel() == 0:
        return []
    cand_vals = C_real.flatten().index_select(0, cand_idx)

    # Sort descending; truncate to n_peaks.
    top_k = min(int(n_peaks), int(cand_vals.numel()))
    sort_vals, sort_perm = torch.sort(cand_vals, descending=True)
    sel_flat_idx = cand_idx.index_select(0, sort_perm[:top_k])
    sel_vals = sort_vals[:top_k]

    # Convert flat → (g, b, a). Periodic axes have already been deduped, so
    # plain integer arithmetic is sufficient.
    nba = n_beta * n_alpha
    ig = sel_flat_idx // nba
    rem = sel_flat_idx - ig * nba
    ib = rem // n_alpha
    ia = rem - ib * n_alpha

    sigmas = (sel_vals - mean) / std

    # Bulk transfer to Python lists, then build dataclasses.
    a_list = alphas.index_select(0, ia).tolist()
    b_list = betas.index_select(0, ib).tolist()
    g_list = gammas.index_select(0, ig).tolist()
    v_list = sel_vals.tolist()
    s_list = sigmas.tolist()
    return [
        RotationPeak(alpha=a, beta=b, gamma=g, score=v, sigma=s)
        for a, b, g, v, s in zip(a_list, b_list, g_list, v_list, s_list)
    ]


