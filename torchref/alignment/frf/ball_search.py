# =============================================================================
# Data containers
# =============================================================================


@dataclass
class BallHarmonicCoefficients:
    """Output of `compute_ball_harmonic_coefficients`."""

    f_plm: torch.Tensor  # complex, shape (P, L, 2L-1)
    L: int
    P: int
    shell_edges: torch.Tensor  # real, shape (P+1,)
    shell_centers: torch.Tensor  # real, shape (P,)
    shell_counts: torch.Tensor  # int64, shape (P,)


@dataclass
class RotationPeak:
    """A single peak of the rotation function."""

    alpha: float
    beta: float
    gamma: float
    score: float       # value of C at the peak (real part)
    sigma: float       # (C - mean) / std at the peak


# =============================================================================
# Forward expansion
# =============================================================================


def compute_ball_harmonic_coefficients(
    s_vectors: torch.Tensor,
    values: torch.Tensor,
    L: int = 48,
    P: int = 24,
    shell_edges: Optional[torch.Tensor] = None,
    d_min: Optional[float] = None,
    d_max: Optional[float] = None,
    enforce_friedel: bool = True,
    zsymm: int = 1,
    skip_odd_l: bool = False,
) -> BallHarmonicCoefficients:
    """
    Compute the ball-harmonic expansion of a real scattered-point field.

    Parameters
    ----------
    s_vectors : (N, 3) real tensor
        Reciprocal-lattice vectors in 1/Å.
    values : (N,) real tensor
        Sample values (e.g. |E(h)|) at each `s_vector`.
    L : int, default 48
        Angular bandlimit.
    P : int, default 24
        Number of radial shells.
    shell_edges : (P+1,) real tensor, optional
        Pre-computed shell boundaries (in |s|). If None, use equal-count
        binning between `d_min` and `d_max` (or full range).
    d_min, d_max : float, optional
        Resolution bounds (Å). When given, reflections outside [1/d_max, 1/d_min]
        in |s| are discarded.
    enforce_friedel : bool, default True
        Augment input with (-s, value) pairs and zero odd-l rows after expansion.

    Returns
    -------
    BallHarmonicCoefficients
    """
    s_mag = s_vectors.norm(dim=-1)
    if d_min is not None or d_max is not None:
        s_lo = 1.0 / d_max if d_max is not None else 0.0
        s_hi = 1.0 / d_min if d_min is not None else float("inf")
        keep = (s_mag >= s_lo) & (s_mag <= s_hi)
        s_vectors = s_vectors[keep]
        values = values[keep]
        s_mag = s_mag[keep]

    if shell_edges is None:
        shell_edges, _ = equal_count_shell_edges(s_mag, P)
    shell_centers = 0.5 * (shell_edges[:-1] + shell_edges[1:])
    shell_idx = assign_shells(s_mag, shell_edges)
    keep = shell_idx >= 0
    s_vectors = s_vectors[keep]
    values = values[keep]
    shell_idx = shell_idx[keep]

    shell_counts = torch.bincount(shell_idx, minlength=P).to(torch.int64)

    f_plm = sh_expand_ball(
        s_vectors, values, shell_idx, P, L,
        enforce_friedel=enforce_friedel,
        zsymm=zsymm, skip_odd_l=skip_odd_l,
    )

    return BallHarmonicCoefficients(
        f_plm=f_plm, L=L, P=P,
        shell_edges=shell_edges,
        shell_centers=shell_centers,
        shell_counts=shell_counts,
    )


# =============================================================================
# Cross-correlation
# =============================================================================


def compute_ball_cross_correlation_coefficients(
    f_obs: BallHarmonicCoefficients,
    f_calc: BallHarmonicCoefficients,
    weights: Optional[torch.Tensor] = None,
) -> torch.Tensor:
    """
    Wigner-D coefficients ξ_{l,m,n} of the rotation function (see module docstring).

    ξ_{l,m,n} = Σ_p w_p · f_{obs}[p, l, n] · conj(f_{calc}[p, l, m])
    """
    assert f_obs.L == f_calc.L, "bandwidths must match"
    assert f_obs.P == f_calc.P, "shell counts must match"
    P, L = f_obs.P, f_obs.L

    if weights is None:
        # Default: weight by shell count (equal weight per reflection).
        counts = f_obs.shell_counts.to(torch.float64)
        w_sum = counts.sum().clamp(min=1.0)
        weights = (counts / w_sum).to(f_obs.f_plm.dtype)
    else:
        weights = weights.to(f_obs.f_plm.dtype)

    xi = torch.einsum(
        "p,pln,plm->lmn",
        weights,
        f_obs.f_plm,
        torch.conj(f_calc.f_plm),
    )
    return xi


