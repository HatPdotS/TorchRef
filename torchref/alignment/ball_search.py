def ball_rotation_search(
    s_obs: torch.Tensor,
    e_obs: torch.Tensor,
    s_calc: torch.Tensor,
    e_calc: torch.Tensor,
    L: int = 48,
    P: int = 24,
    n_peaks: int = 200,
    d_min: Optional[float] = None,
    d_max: Optional[float] = None,
    refine_subvoxel: bool = True,
    n_refine: int = 20,
    sigma_threshold: float = 1.0,
    weights: Optional[torch.Tensor] = None,
    auto_variance_weights: bool = True,
) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, List[RotationPeak]]:
    """
    End-to-end Patterson rotation search.

    Parameters
    ----------
    s_obs, s_calc : (N, 3) real
        Reciprocal-lattice vectors. Need not be the same set of HKLs for obs
        and calc — but should sample the same resolution range.
    e_obs, e_calc : (N,) real
        Normalized structure-factor amplitudes (E-values). Pass |F|² instead
        if you want a strict Patterson rotation function.
    L, P : int, default 48 / 24
        Bandlimit and shell count.
    d_min, d_max : float
        Resolution limits in Å (s_min = 1/d_max, s_max = 1/d_min).
    n_peaks : int, default 200
        Number of rotation peaks to return.
    refine_subvoxel : bool, default True
        If True, refine the top `n_refine` peaks by gradient ascent on the
        pointwise rotation function (autograd, no FFT).
    n_refine : int
        Number of peaks to refine.
    sigma_threshold : float
        Minimum (peak - mean)/std for a peak to be kept.
    weights : (P,) real, optional
        Per-shell weights in the cross-correlation. Default: shell-count weighted,
        or (when `auto_variance_weights=True`) inverse-sqrt of the empirical
        per-shell variance of the obs Patterson coefficient.
    auto_variance_weights : bool, default True
        Compute `weights = 1/√Var(e_obs)_p` per shell when no explicit `weights`
        are supplied. This is the LERF1-style empirical variance correction —
        downweights shells whose observed Patterson coefficient is dominated by
        intermolecular contributions (high-symmetry crystals).

    Returns
    -------
    C : complex tensor (n_gamma, n_beta, n_alpha)
        Rotation function on Euler grid (Edmonds order).
    alphas, betas, gammas : real 1-D tensors
        Grid coordinates.
    peaks : list of RotationPeak (sorted by descending score)
    """
    f_obs = compute_ball_harmonic_coefficients(
        s_obs, e_obs, L=L, P=P, d_min=d_min, d_max=d_max,
    )
    # Share shell edges between obs and calc — required for the cross-correlation
    # to be meaningful (same radial binning on both sides).
    f_calc = compute_ball_harmonic_coefficients(
        s_calc, e_calc, L=L, P=P, shell_edges=f_obs.shell_edges,
    )

    if auto_variance_weights and weights is None:
        s_mag_obs = s_obs.norm(dim=-1)
        if d_min is not None or d_max is not None:
            s_lo = 1.0 / d_max if d_max is not None else 0.0
            s_hi = 1.0 / d_min if d_min is not None else float("inf")
            keep_obs = (s_mag_obs >= s_lo) & (s_mag_obs <= s_hi)
            s_mag_v = s_mag_obs[keep_obs]
            e_obs_v = e_obs[keep_obs]
        else:
            s_mag_v = s_mag_obs
            e_obs_v = e_obs
        shell_idx_v = assign_shells(s_mag_v, f_obs.shell_edges)
        shell_var = compute_patterson_shell_variance(
            e_obs_v.to(torch.float64), shell_idx_v, P=P,
        )
        w = 1.0 / shell_var.sqrt()
        w = w * (P / w.sum().clamp(min=1e-30))
        weights = w.to(f_obs.f_plm.real.dtype)

    xi = compute_ball_cross_correlation_coefficients(f_obs, f_calc, weights=weights)
    C, alphas, betas, gammas = evaluate_rotation_function_grid(
        xi, L, n_alpha=2 * L, n_beta=2 * L, n_gamma=2 * L,
    )
    peaks = find_rotation_peaks(
        C, alphas, betas, gammas,
        n_peaks=n_peaks, sigma_threshold=sigma_threshold,
    )
    if refine_subvoxel and len(peaks) > 0:
        head = peaks[:n_refine]
        head = refine_peaks_subvoxel(head, C, alphas, betas, gammas)
        peaks = head + peaks[n_refine:]
        peaks.sort(key=lambda r: r.score, reverse=True)
    return C, alphas, betas, gammas, peaks


# =============================================================================
# Convenience: Euler ↔ matrix using the Edmonds ZYZ convention
# =============================================================================


def rotation_matrix_from_edmonds_euler_batch(
    alpha: torch.Tensor, beta: torch.Tensor, gamma: torch.Tensor,
) -> torch.Tensor:
    """
    Vectorised Edmonds ZYZ Euler → R: R = R_z(α) R_y(β) R_z(γ).

    `alpha`, `beta`, `gamma`: identically-shaped real tensors. Returns
    `(..., 3, 3)` in the same dtype/device as the inputs. Equivalent to
    calling `rotation_matrix_from_edmonds_euler` per Euler triple, but
    avoids 9 small-tensor allocations per call.
    """
    ca, sa = torch.cos(alpha), torch.sin(alpha)
    cb, sb = torch.cos(beta), torch.sin(beta)
    cg, sg = torch.cos(gamma), torch.sin(gamma)
    zero = torch.zeros_like(alpha)
    one = torch.ones_like(alpha)
    Rz_a = torch.stack([
        torch.stack([ca, -sa, zero], dim=-1),
        torch.stack([sa,  ca, zero], dim=-1),
        torch.stack([zero, zero, one], dim=-1),
    ], dim=-2)
    Ry_b = torch.stack([
        torch.stack([cb,  zero, sb], dim=-1),
        torch.stack([zero, one, zero], dim=-1),
        torch.stack([-sb, zero, cb], dim=-1),
    ], dim=-2)
    Rz_c = torch.stack([
        torch.stack([cg, -sg, zero], dim=-1),
        torch.stack([sg,  cg, zero], dim=-1),
        torch.stack([zero, zero, one], dim=-1),
    ], dim=-2)
    return Rz_a @ Ry_b @ Rz_c


def rotation_matrix_from_edmonds_euler(
    alpha: float, beta: float, gamma: float, dtype=torch.float64,
) -> torch.Tensor:
    """
    Build R = R_z(α) R_y(β) R_z(γ)   (Edmonds active ZYZ).

    Equivalent to passing `[γ, β, α]` to
    `torchref.alignment.transform.rotation_matrix_from_euler`.
    """
    ca, sa = math.cos(alpha), math.sin(alpha)
    cb, sb = math.cos(beta), math.sin(beta)
    cg, sg = math.cos(gamma), math.sin(gamma)
    Rz_a = torch.tensor([[ca, -sa, 0.0], [sa, ca, 0.0], [0.0, 0.0, 1.0]], dtype=dtype)
    Ry_b = torch.tensor([[cb, 0.0, sb], [0.0, 1.0, 0.0], [-sb, 0.0, cb]], dtype=dtype)
    Rz_c = torch.tensor([[cg, -sg, 0.0], [sg, cg, 0.0], [0.0, 0.0, 1.0]], dtype=dtype)
    return Rz_a @ Ry_b @ Rz_c


def edmonds_euler_from_rotation_matrix(R: torch.Tensor) -> Tuple[float, float, float]:
    """
    Recover (α, β, γ) such that R = R_z(α) R_y(β) R_z(γ).
    Returns angles in radians; α, γ ∈ [0, 2π), β ∈ [0, π].
    Singular when β = 0 or π (only α+γ is determined); we set γ=0 in those cases.
    """
    R = R.to(torch.float64)
    cos_beta = R[2, 2].clamp(-1.0, 1.0).item()
    beta = math.acos(cos_beta)
    sin_beta = math.sin(beta)
    if abs(sin_beta) < 1e-9:
        # Degenerate: only α+γ is determined. Set γ=0.
        alpha = math.atan2(R[1, 0].item(), R[0, 0].item())
        gamma = 0.0
    else:
        alpha = math.atan2(R[1, 2].item(), R[0, 2].item())
        gamma = math.atan2(R[2, 1].item(), -R[2, 0].item())
    alpha = alpha % (2.0 * math.pi)
    gamma = gamma % (2.0 * math.pi)
    return alpha, beta, gamma


def rotation_angular_distance_deg(R1: torch.Tensor, R2: torch.Tensor) -> float:
    """Geodesic distance on SO(3) in degrees: arccos((tr(R1 R2^T) - 1)/2)."""
    R = R1.to(torch.float64) @ R2.to(torch.float64).T
    tr = (R[0, 0] + R[1, 1] + R[2, 2]).clamp(-1.0, 3.0).item()
    cos_a = max(-1.0, min(1.0, (tr - 1.0) / 2.0))
    return math.degrees(math.acos(cos_a))
