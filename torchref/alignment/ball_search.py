# Peak finding
# =============================================================================


def _circular_pad_gamma_alpha(x: torch.Tensor, r: int) -> torch.Tensor:
    """
    Wrap-pad axes 0 (γ) and -1 (α) by `r` voxels using circular boundary
    conditions, and constant-pad axis 1 (β) with -inf (non-periodic).
    Input shape (Γ, B, Α); output shape (Γ+2r, B+2r, Α+2r).
    """
    if r <= 0:
        return x
    x = torch.cat([x[-r:], x, x[:r]], dim=0)                    # wrap γ
    x = torch.cat([x[..., -r:], x, x[..., :r]], dim=-1)         # wrap α
    pad_shape = list(x.shape)
    pad_shape[1] = r
    neg_inf = torch.full(pad_shape, float("-inf"), dtype=x.dtype, device=x.device)
    x = torch.cat([neg_inf, x, neg_inf], dim=1)                 # β: -inf pad
    return x


def find_rotation_peaks(
    C: torch.Tensor,
    alphas: torch.Tensor,
    betas: torch.Tensor,
    gammas: torch.Tensor,
    n_peaks: int = 200,
    sigma_threshold: float = 0.0,
    cluster_radius_voxels: int = 2,
) -> List[RotationPeak]:
    """
    Extract local maxima of `C` and return them sorted by descending value.

    Periodic in α and γ (FFT axes); β is non-periodic but mirror at the
    endpoints isn't enforced — the user is expected to oversample β.

    Patterson centrosymmetry C(R) = C(-R) is left to the caller — when needed,
    add a post-processing step that merges peaks with R and -R representations.

    Vectorised over voxels: NMS is implemented as `C == max_pool3d(C)` with
    `kernel = 2·r + 1`, circular in α and γ. The legacy per-voxel Python loop
    with per-iteration `.item()` is replaced with a single sort + bulk
    `.tolist()` at the end — same semantics on randomly-real data (exact
    ties are vanishingly rare), but device-portable and ~1-2 orders of
    magnitude faster.
    """
    C_real = C.real
    n_gamma, n_beta, n_alpha = C_real.shape
    flat_stats = C_real.flatten()

    mean = flat_stats.mean()
    std = flat_stats.std().clamp(min=1e-30)
    threshold = mean + sigma_threshold * std

    r = int(cluster_radius_voxels)
    if r > 0:
        padded = _circular_pad_gamma_alpha(C_real, r)
        # max_pool3d wants (N, C, D, H, W). Add batch+channel dims, then strip.
        pooled = F.max_pool3d(
            padded.unsqueeze(0).unsqueeze(0),
            kernel_size=2 * r + 1, stride=1, padding=0,
        )[0, 0]
        is_local_max = C_real >= pooled
    else:
        is_local_max = torch.ones_like(C_real, dtype=torch.bool)

    above_threshold = C_real >= threshold
    candidate = is_local_max & above_threshold
    candidate_flat = candidate.flatten()
    cand_idx = candidate_flat.nonzero(as_tuple=False).flatten()
    if cand_idx.numel() == 0:
        return []
    cand_vals = C_real.flatten().index_select(0, cand_idx)

    # Sort descending; truncate to n_peaks.
    top_k = min(int(n_peaks), int(cand_vals.numel()))
    sort_vals, sort_perm = torch.sort(cand_vals, descending=True)
    sel_flat_idx = cand_idx.index_select(0, sort_perm[:top_k])
    sel_vals = sort_vals[:top_k]

    # Convert flat → (g, b, a). Periodic axes have already been deduped, so
    # plain integer arithmetic is sufficient.
    nba = n_beta * n_alpha
    ig = sel_flat_idx // nba
    rem = sel_flat_idx - ig * nba
    ib = rem // n_alpha
    ia = rem - ib * n_alpha

    sigmas = (sel_vals - mean) / std

    # Bulk transfer to Python lists, then build dataclasses.
    a_list = alphas.index_select(0, ia).tolist()
    b_list = betas.index_select(0, ib).tolist()
    g_list = gammas.index_select(0, ig).tolist()
    v_list = sel_vals.tolist()
    s_list = sigmas.tolist()
    return [
        RotationPeak(alpha=a, beta=b, gamma=g, score=v, sigma=s)
        for a, b, g, v, s in zip(a_list, b_list, g_list, v_list, s_list)
    ]


# =============================================================================
# Sub-voxel refinement (pointwise gradient ascent on C(R) using autograd)
# =============================================================================


def _parabolic_offset_vec(
    y_minus: torch.Tensor, y_zero: torch.Tensor, y_plus: torch.Tensor,
) -> torch.Tensor:
    """
    Vectorised sub-voxel offset for a quadratic through three samples
    y(-1), y(0), y(+1). Returns δ clamped to [-1, 1]; degenerate cells
    (|denom| < 1e-30) get δ = 0.
    """
    denom = y_minus - 2.0 * y_zero + y_plus
    bad = denom.abs() < 1e-30
    safe_denom = torch.where(bad, torch.ones_like(denom), denom)
    delta = 0.5 * (y_minus - y_plus) / safe_denom
    delta = torch.where(bad, torch.zeros_like(delta), delta)
    return delta.clamp(-1.0, 1.0)


def refine_peaks_subvoxel(
    peaks: List[RotationPeak],
    C: torch.Tensor,
    alphas: torch.Tensor,
    betas: torch.Tensor,
    gammas: torch.Tensor,
) -> List[RotationPeak]:
    """
    Sub-voxel refinement of integer-grid peaks by separable quadratic fitting.

    For each peak, fits y = a + b·δ + c·δ² through the values at ±1 voxel along
    each of α, β, γ axes (α and γ periodic with the grid length, β not).
    Returns refined peaks with interpolated angles and values.

    Vectorised over all peaks: indices and neighbour samples are gathered in
    a single batched op; the legacy per-peak `.item()` loop is replaced with
    one `.tolist()` at the end (cuts ~12·K scalar GPU↔CPU round-trips).
    """
    if not peaks:
        return list(peaks)

    n_gamma, n_beta, n_alpha = C.shape
    Cr = C.real
    device = Cr.device
    real_dtype = alphas.dtype

    dalpha = (alphas[1] - alphas[0]).item()
    dgamma = (gammas[1] - gammas[0]).item()
    dbeta = (betas[1] - betas[0]).item() if betas.numel() > 1 else 0.0
    a0 = alphas[0].item()
    g0 = gammas[0].item()
    b0 = betas[0].item()

    # Pack peak coordinates into tensors in one go.
    K = len(peaks)
    alpha_in = torch.tensor([p.alpha for p in peaks], dtype=real_dtype, device=device)
    beta_in = torch.tensor([p.beta for p in peaks], dtype=real_dtype, device=device)
    gamma_in = torch.tensor([p.gamma for p in peaks], dtype=real_dtype, device=device)

    # Integer voxel indices.
    ia = ((alpha_in - a0) / dalpha).round().long() % n_alpha
    ig = ((gamma_in - g0) / dgamma).round().long() % n_gamma
    if dbeta > 0:
        ib = ((beta_in - b0) / dbeta).round().long().clamp(0, n_beta - 1)
    else:
        ib = torch.zeros(K, dtype=torch.long, device=device)

    am = (ia - 1) % n_alpha
    ap = (ia + 1) % n_alpha
    gm = (ig - 1) % n_gamma
    gp = (ig + 1) % n_gamma
    # β neighbours: clamp at boundaries; we zero δβ explicitly there below.
    ibm = (ib - 1).clamp(min=0, max=n_beta - 1)
    ibp = (ib + 1).clamp(min=0, max=n_beta - 1)

    y0 = Cr[ig, ib, ia]
    ya_m = Cr[ig, ib, am]
    ya_p = Cr[ig, ib, ap]
    yg_m = Cr[gm, ib, ia]
    yg_p = Cr[gp, ib, ia]
    yb_m = Cr[ig, ibm, ia]
    yb_p = Cr[ig, ibp, ia]

    da = _parabolic_offset_vec(ya_m, y0, ya_p)
    dg = _parabolic_offset_vec(yg_m, y0, yg_p)
    db = _parabolic_offset_vec(yb_m, y0, yb_p)
    # Zero out β offset at the boundary (single-sided / undefined).
    at_b_boundary = (ib == 0) | (ib == n_beta - 1)
    db = torch.where(at_b_boundary, torch.zeros_like(db), db)
    if dbeta <= 0:
        db = torch.zeros_like(db)

    two_pi = 2.0 * math.pi
    alpha_new = (alphas.index_select(0, ia) + da * dalpha) % two_pi
    gamma_new = (gammas.index_select(0, ig) + dg * dgamma) % two_pi
    beta_new = (betas.index_select(0, ib) + db * dbeta).clamp(min=0.0, max=math.pi)

    a_list = alpha_new.tolist()
    b_list = beta_new.tolist()
    g_list = gamma_new.tolist()
    return [
        RotationPeak(
            alpha=a, beta=b, gamma=g, score=p.score, sigma=p.sigma,
        )
        for a, b, g, p in zip(a_list, b_list, g_list, peaks)
    ]


